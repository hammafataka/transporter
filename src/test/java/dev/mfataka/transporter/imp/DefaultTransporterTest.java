package dev.mfataka.transporter.imp;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import java.util.Map;
import java.util.concurrent.TimeUnit;

import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.mockito.ArgumentMatchers;
import org.mockito.Mockito;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.web.reactive.function.client.WebClient;

import dev.mfataka.transporter.config.TransporterConfiguration;
import dev.mfataka.transporter.enums.TransporterMethod;
import dev.mfataka.transporter.filters.KibanaLoggingFilter;
import dev.mfataka.transporter.utils.KibanaMarker;

class DefaultTransporterTest {

    private static TransporterConfiguration cfg() {
        return TransporterConfiguration.builder().timeUnit(TimeUnit.SECONDS).build();
    }

    private static WebClient mockClient() {
        var wc = mock(WebClient.class);
        var uriSpec = mock(WebClient.RequestBodyUriSpec.class);
        var bodySpec = mock(WebClient.RequestBodySpec.class);
        when(wc.post()).thenReturn(uriSpec);
        when(wc.put()).thenReturn(uriSpec);
        when(wc.method(any(HttpMethod.class))).thenReturn(uriSpec);
        when(uriSpec.uri(any(String.class))).thenReturn(bodySpec);
        when(bodySpec.header(any(), any())).thenReturn(bodySpec);
        when(bodySpec.contentType(any())).thenReturn(bodySpec);
        return wc;
    }

    @Test
    void withHeader_returnsNewInstance_originalUnchanged() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null);
        var t2 = t1.withHeader("X-A", "1");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void withUrlParam_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.POST, null);
        var t2 = t1.withUrlParam("k", "v");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void basicAuth_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null);
        var t2 = t1.basicAuth("u", "p");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void bearerAuth_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null);
        var t2 = t1.bearerAuth("token");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void method_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null);
        var t2 = t1.method(TransporterMethod.POST);
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void bodyValue_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.POST, null);
        var t2 = t1.bodyValue("body");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void contentType_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.POST, null);
        var t2 = t1.contentType(MediaType.APPLICATION_JSON);
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    void withOperator_returnsNewInstance() {
        var t1 = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null);
        var t2 = t1.withOperator("o2");
        assertThat(t1).isNotSameAs(t2);
    }

    @Test
    @SuppressWarnings("unchecked")
    void send_withKibanaLoggingEnabled_setsMarkersAttribute() {
        var wc = mockClient();
        var cfg = TransporterConfiguration.builder()
                .timeUnit(TimeUnit.SECONDS)
                .kibanaLoggingEnabled(true)
                .operator("built-operator")
                .build();
        var bodySpec = wc.post().uri("/path");

        DefaultTransporter.initial(wc, cfg, TransporterMethod.POST, null)
                .send("/path");

        var captor = ArgumentCaptor.forClass(Object.class);
        Mockito.verify(bodySpec).attribute(ArgumentMatchers.eq(KibanaLoggingFilter.MARKERS_ATTRIBUTE), captor.capture());
        var markers = (Map<KibanaMarker, String>) captor.getValue();
        assertThat(markers)
                .containsEntry(KibanaMarker.OPERATOR, "built-operator")
                // the correlation id is generated by the filter, never resolved here
                .doesNotContainKey(KibanaMarker.CORRELATION_ID);
    }

    @Test
    @SuppressWarnings("unchecked")
    void send_perCallOperator_overridesBuiltOperator() {
        var wc = mockClient();
        var cfg = TransporterConfiguration.builder()
                .timeUnit(TimeUnit.SECONDS)
                .kibanaLoggingEnabled(true)
                .operator("built-operator")
                .build();
        var bodySpec = wc.post().uri("/path");

        DefaultTransporter.initial(wc, cfg, TransporterMethod.POST, null)
                .withOperator("per-call-operator")
                .send("/path");

        var captor = ArgumentCaptor.forClass(Object.class);
        Mockito.verify(bodySpec).attribute(ArgumentMatchers.eq(KibanaLoggingFilter.MARKERS_ATTRIBUTE), captor.capture());
        var markers = (Map<KibanaMarker, String>) captor.getValue();
        assertThat(markers).containsEntry(KibanaMarker.OPERATOR, "per-call-operator");
    }

    @Test
    void send_withKibanaLoggingDisabled_doesNotSetAttribute() {
        var wc = mockClient();
        var bodySpec = wc.post().uri("/path");

        DefaultTransporter.initial(wc, cfg(), TransporterMethod.POST, null).send("/path");

        org.mockito.Mockito.verify(bodySpec, org.mockito.Mockito.never()).attribute(any(), any());
    }

    @Test
    void sendDoesNotResetState_canBeCalledMultipleTimes() {
        var t = DefaultTransporter.initial(mockClient(), cfg(), TransporterMethod.GET, null)
                .withHeader("X-A", "1");
        t.send("/path");
        t.send("/path");
        t.send("/path");
        // No exception means we can call send repeatedly on the same Transporter.
    }
}
